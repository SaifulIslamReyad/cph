L = [4, 8, 15, 16, 23, 42]
d = {} 
for i in range(len(L)):
    for j in range(i + 1, len(L)): 
        d[L[i] * L[j]] = {L[i], L[j]}

print("? 1 2", "? 2 3", "? 4 5", "? 5 6", sep="\n")
r = []
for _ in range(2):
    p1 = int(input())
    p2 = int(input())

    x, y = d[p1], d[p2]

    r.extend(x - y) 
    r.extend(x & y) 
    r.extend(y - x) 

print("!", *r)



